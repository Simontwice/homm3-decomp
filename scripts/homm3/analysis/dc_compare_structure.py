"""Side-by-side source structure: the Dreamcast reference against our C++.

`homm3 dreamcast compare-structure` writes, for every selected retail
function with a Dreamcast pairing, two files with one shared layout:

* `<fn>.dc.cpp`: the Dreamcast structure (`dc_structure.function_payload`);
* `<fn>.ours.cpp`: the same sections built from our authored definition
  (Clang AST through `source_facts.CandidateParser`, as `diff-locals` uses)
  and our compiled candidate object.

The aligned sections are normalized so that a plain `diff -u` shows only
differences that mean something: line numbers are relative to the body's
opening brace (Dreamcast: the procedure boundary row), names use the
documented case/underscore/Hungarian folding, types drop `class`/`struct`
keywords and spacing, and every section is sorted the same way on both
sides. Each file ends with a side-specific REFERENCE section (the full
exporter stub, or our numbered source text and x86 block skeleton) that is
not meant to align.

The Dreamcast build is an older SH4 revision. Every difference is a lead
for a VC6 experiment, never a source verdict; scores are not touched.
"""
from __future__ import annotations

from collections import Counter, defaultdict
import json
from pathlib import Path
import re
import subprocess
import tempfile
from typing import Any, Iterable

from homm3.analysis import dc_callees, dc_diff_locals, dc_structure, dreamcast
from homm3.analysis.source_facts import name_key, semantic_name_key, type_facts

SCHEMA = "homm3.dreamcast-compare-structure.v1"
GENERATOR = "homm3 dreamcast compare-structure"
BANNER = "// GENERATED by homm3 dreamcast compare-structure; regenerate, do not edit."
CAUTION = (
    "Dreamcast is an older SH4 revision of the source. Differences are leads "
    "for VC6 experiments, never source verdicts; keep a change only when retail "
    "bytes and the remaining evidence agree."
)
SIDES = ("dc", "ours")


# --- normalization ------------------------------------------------------------------

_DEFAULT_ARGUMENTS = re.compile(r",std::(?:char_traits|allocator)<")


def _drop_default_arguments(text: str) -> str:
    """`std::vector<T,std::allocator<T>>` and the char_traits/allocator tail
    of basic_string are what VC6 and CodeView spell out; Clang may not."""
    while match := _DEFAULT_ARGUMENTS.search(text):
        depth, end = 0, match.end() - 1
        for end in range(match.end() - 1, len(text)):
            depth += {"<": 1, ">": -1}.get(text[end], 0)
            if depth == 0:
                break
        text = text[:match.start()] + text[end + 1:]
    return {"std::string": "std::basic_string<char>"}.get(text, text)


def norm_type(text: str) -> str:
    """One spelling per type: no class/struct keywords, canonical cv and spacing."""
    text = " ".join(str(text).split())
    facts = type_facts(text)
    if facts is None:
        return re.sub(r"\b(?:class|struct|union|enum)\s+", "", text)
    base = _drop_default_arguments(re.sub(r"\s*(::|[<>,*&])\s*", r"\1", facts.base))
    base = {"__int64": "long long", "unsigned __int64": "unsigned long long"}.get(base, base)
    out = ("const " if "const" in facts.qualifiers[0] else "") + base
    for index, pointer in enumerate(facts.indirections):
        out += pointer + (" const" if "const" in facts.qualifiers[index + 1] else "")
    return out + "".join(f"[{extent}]" for extent in facts.arrays)


def same_type(dreamcast: str, ours: str) -> bool:
    """Equal after Dreamcast's lowering of `bool` to its unsigned-byte record."""
    lowered = re.sub(r"\bbool\b", "unsigned char", ours)
    return dreamcast in (ours, lowered)


def callee_token(name: str | None) -> str | None:
    """Normalized callee spelling; None for runtime/library plumbing."""
    identity = dc_callees.callee(name) if name else None
    if identity is None:
        return None
    return {"constructor": "ctor:", "destructor": "dtor:"}.get(identity.kind, "") + \
        identity.key.removeprefix("~")


def statement_runs(lines: Iterable[int]) -> tuple[int, int]:
    """(runs, lines) of non-statement lines between the first and last statement."""
    ordered = sorted(set(lines))
    runs = missing = 0
    for left, right in zip(ordered, ordered[1:]):
        if right > left + 1:
            runs += 1
            missing += right - left - 1
    return runs, missing


def span_label(span: tuple[int, int] | None) -> str:
    return "+?" if span is None else f"{span[0]:+04d}..{span[1]:+04d}"


def _empty_view(side: str) -> dict[str, Any]:
    return {"side": side, "provenance": [], "gaps": [], "signature": "", "parameters": [],
            "locals": [], "temporaries": Counter(), "other_temporaries": Counter(),
            "statement_lines": set(), "scopes": [], "calls_by_line": defaultdict(list),
            "callees": defaultdict(lambda: {"calls": 0, "inline": 0}), "control": None,
            "reference": ""}


def _signature(returns: str | None, name: str, parameters: list[tuple[str, str]],
               method_cv: Iterable[str]) -> str:
    head = "(ctor/dtor)" if returns is None else norm_type(returns)
    cv = "".join(" " + q for q in sorted(method_cv))
    return f"{head} {name_key(name.rsplit('::', 1)[-1])}({', '.join(t for _n, t in parameters)}){cv}"


# --- Dreamcast side --------------------------------------------------------------------

def dreamcast_view(corpus, row, *, symbols, data, types) -> dict[str, Any]:
    from homm3.analysis import source_facts
    view = _empty_view("dc")
    payload = dc_structure.function_payload(corpus, row, symbols, data, types)
    dossier = dreamcast.build_dossier(corpus, row, dump=symbols, data=data, type_table=types)
    shape = payload["debug_shape"]
    fn = shape["function"]
    owner = dreamcast._source_key(fn["source"]["file"])
    base = fn["source"]["boundary_line"]
    view["base_line"] = base
    view["provenance"] = [
        f"// SIDE: Dreamcast {row['module']} dc:0x{fn['address']:08x} "
        f"({fn['emitted_size']} SH4 bytes); {fn['source']['file']}:{base} is relative line +000"]

    procedure = symbols.procedures[fn["address"]]
    expected = source_facts.expected_facts(dossier, procedure, types)
    view["gaps"].extend(expected["gaps"])
    view["parameters"] = [(semantic_name_key(p["name"]) if p["name"] else f"#{i}", norm_type(p["type"]))
                          for i, p in enumerate(expected["parameters"])]
    view["signature"] = _signature(expected.get("return"), procedure.name, view["parameters"],
                                   expected.get("method_cv", ()))

    statements = sorted(shape["statements"], key=lambda s: s["address"])
    owning = [s for s in statements if dreamcast._source_key(s["source"]["file"]) == owner]
    view["statement_lines"] = {s["source"]["line"] - base for s in owning}

    def lines_in(start: int, end: int) -> tuple[int, int] | None:
        hits = [s["source"]["line"] - base for s in owning
                if s["address"] < max(end, start + 1) and s["address"] + max(s["emitted_size"], 1) > start]
        return (min(hits), max(hits)) if hits else None

    spans = {scope["id"]: lines_in(scope["address"], scope["address"] + scope["size"])
             for scope in payload["scopes"]}
    children = defaultdict(list)
    for scope in payload["scopes"]:
        children[scope["parent_id"]].append(scope)

    def walk(parent: str, depth: int) -> None:
        for scope in sorted(children[parent], key=lambda s: (s["address"], -s["size"], s["record_offset"])):
            view["scopes"].append({"span": spans[scope["id"]], "depth": depth,
                                   "key": (scope["address"], scope["size"])})
            walk(scope["id"], depth + 1)
    walk("function", 0)

    scope_label = {"function": "function", **{key: span_label(span) for key, span in spans.items()}}
    for var in payload["variables"]:
        if var["kind"] != "local" or var["name"] in ("this", "__$ReturnUdt"):
            continue
        view["locals"].append({"name": var["name"], "type": norm_type(types.declaration(var["type_index"])),
                               "scope": scope_label.get(var["scope_id"], var["scope_id"])})

    clue_rows = dreamcast._inline_clue_rows(corpus, row, symbols.source_lines.get(row["module"], ()))
    view["temporaries"] = Counter(dc_diff_locals.dc_inventory(dossier, clue_rows)["temporaries"])

    def owning_line(address: int) -> int:
        line = 0
        for statement in owning:
            if statement["address"] > address:
                break
            line = statement["source"]["line"] - base
        return line

    current = 0
    for statement in statements:
        if dreamcast._source_key(statement["source"]["file"]) == owner:
            current = statement["source"]["line"] - base
        for call in statement["calls"]:
            token = callee_token(call["name"])
            if token is None:
                continue
            view["callees"][token]["calls"] += 1
            if not token.startswith("dtor:"):
                view["calls_by_line"][current].append(token)
    for group in payload["inline_evidence"]:
        keys = sorted({token for name in group.get("definitions", ())
                       if (token := callee_token(name))})
        if not keys:
            continue
        token = "|".join(keys)
        view["callees"][token]["inline"] += 1
        view["calls_by_line"][owning_line(group["address"])].append("inline:" + token)

    blocks = payload["cfg"]
    sites = [site for block in blocks for site in block["control_sites"]]
    view["control"] = {
        "blocks": len(blocks),
        "conditional branches": sum(bool(site.get("conditional_branch")) for site in sites),
        "back edges": sum(1 for block in blocks for succ in block["successors"] if succ <= block["start"]),
        "exit blocks": sum(1 for block in blocks if not block["successors"]),
        "direct calls": sum(site.get("call_target_va") is not None for site in sites),
        "indirect calls": sum("call_target_va" in site and site["call_target_va"] is None for site in sites),
    }
    view["reference"] = dc_structure.render_function(payload, types)
    return view


# --- our side ---------------------------------------------------------------------------

def _line_class(text: str, in_comment: bool) -> tuple[str, bool]:
    stripped = text.strip()
    if in_comment:
        return "comment", "*/" not in stripped
    if not stripped:
        return "blank", False
    if stripped.startswith("//"):
        return "comment", False
    if stripped.startswith("/*"):
        return "comment", "*/" not in stripped
    if re.fullmatch(r"[{}];?", stripped):
        return "brace", False
    if stripped.startswith("#"):
        return "preprocessor", False
    return "code", False


class ObjectCalls:
    """Direct calls and the x86 block skeleton of our compiled candidate bodies."""

    def __init__(self):
        self.listings: dict[Path, tuple[str, set[str], dict[str, str]] | None] = {}

    def body(self, obj: Path, symbol: str) -> str | None:
        from homm3.sema import _asm
        if obj not in self.listings:
            self.listings[obj] = None
            if obj.is_file():
                run = subprocess.run(["llvm-objdump", "-dr", "--x86-asm-syntax=intel", str(obj)],
                                     capture_output=True, text=True)
                names = subprocess.run(["llvm-nm", "-P", str(obj)], capture_output=True, text=True)
                if run.returncode == 0 and names.returncode == 0:
                    # Public names and function symbols bound a body; $L labels do not.
                    public = {fields[0] for line in names.stdout.splitlines()
                              if len(fields := line.split()) >= 3 and fields[1] == "T"}
                    targets = re.findall(r"IMAGE_REL_I386_REL32\s+(\S+)", run.stdout)
                    self.listings[obj] = (run.stdout, public | _asm._function_text_symbols(obj),
                                          undecorate(targets))
        listing = self.listings[obj]
        if listing is None:
            return None
        return _asm._slice_public_symbol(listing[0], symbol, 0, listing[1])

    def qualified(self, obj: Path) -> dict[str, str]:
        listing = self.listings.get(obj)
        return listing[2] if listing else {}


_CALLING = re.compile(r"\b__(?:thiscall|cdecl|stdcall|fastcall)\s+")


def undecorate(names: Iterable[str]) -> dict[str, str]:
    """Qualified source names of MSVC-decorated symbols (llvm-undname).

    `dc_callees` reads only the leading scope of a decorated name, so a
    template scope such as `?insert@?$vector@PAVwidget@@...@std@@` would lose
    its `std` owner; the full undecoration keeps library calls out."""
    names = sorted({name for name in names if name.startswith("?")})
    if not names:
        return {}
    try:
        run = subprocess.run(["llvm-undname"], input="\n".join(names) + "\n",
                             capture_output=True, text=True)
    except OSError:
        return {}
    out, wanted, decorated = {}, set(names), None
    for text in run.stdout.splitlines():
        if text in wanted:
            decorated = text
            continue
        match = _CALLING.search(text) if decorated else None
        if not match:
            continue
        rest, depth = text[match.end():], 0
        for index, char in enumerate(rest):
            depth += {"<": 1, ">": -1}.get(char, 0)
            if char == "(" and depth == 0:
                out[decorated] = rest[:index].strip()
                break
        decorated = None
    return out


def compiled_facts(text: str, qualified: dict[str, str] | None = None) -> dict[str, Any]:
    from homm3.sema import _asm
    qualified = qualified or {}
    code = {offset for offset, _instruction in _asm.code_insns(text)}
    direct, emitted, indirect = Counter(), 0, 0
    for offset, _raw, body, relocs in _asm.reloc_rows(text):
        if offset not in code or body.split(None, 1)[0].lower() != "call":
            continue
        target = next((symbol for _site, kind, symbol in relocs if kind == "REL32"), None)
        if target is None:
            indirect += 1
            continue
        emitted += 1
        token = callee_token(qualified.get(target, target))
        if token is not None:
            direct[token] += 1
    graph = _asm.cfg(text)
    terms = [term or "" for _address, _body, term in graph]
    return {"direct": direct, "control": {
        "blocks": len(graph),
        "conditional branches": sum(term.startswith("jcc") for term in terms),
        "back edges": sum(term.count("^") for term in terms),
        "exit blocks": sum(term in ("ret", "end", "jmp <ext>") for term in terms),
        "direct calls": emitted,
        "indirect calls": indirect,
    }, "skeleton": _asm.blocks(text)}


def our_view(candidate: dict[str, Any], source: str, compiled: dict[str, Any] | None,
             *, object_note: str, display_path: str) -> dict[str, Any]:
    view = _empty_view("ours")
    layout = candidate["layout"]
    base = layout["begin_line"]
    view["base_line"] = base
    view["provenance"] = [f"// SIDE: ours {display_path}:{base} is relative line +000; {object_note}"]
    view["gaps"].extend(gap.splitlines()[0] for gap in candidate.get("gaps", []))
    view["parameters"] = [(semantic_name_key(p["name"]) if p["name"] else f"#{i}", norm_type(p["type"]))
                          for i, p in enumerate(candidate.get("parameters", []))]
    view["signature"] = _signature(candidate.get("return"), candidate.get("name") or "",
                                   view["parameters"], candidate.get("method_cv", ()))
    view["statement_lines"] = {row["line"] - base for row in layout["statements"]}
    spans = [(scope["begin_line"] - base, scope["end_line"] - base) for scope in layout["scopes"]]
    depth: dict[int, int] = {}
    for index, scope in enumerate(layout["scopes"]):
        depth[index] = 0 if scope["parent"] is None else depth[scope["parent"]] + 1
        # A braced substatement and its block are one extent, as on Dreamcast.
        view["scopes"].append({"span": spans[index], "depth": depth[index],
                               "key": (*spans[index], scope.get("kind") == "statement")})
    declarations = {int(offset): scope for offset, scope in layout["declarations"].items()}
    for local in candidate.get("locals", []):
        scope = declarations.get(local.get("offset"))
        view["locals"].append({"name": local["name"], "aliases": local.get("aliases", []),
                               "type": norm_type(local["type"]),
                               "scope": "function" if scope is None else span_label(spans[scope])})
    for temporary in candidate.get("temporaries", []):
        target = view["temporaries"] if temporary.get("destructor") else view["other_temporaries"]
        target[dc_callees.type_key(temporary["type"])] += 1

    statement_of = {int(offset): line for offset, line in layout["calls"].items()}
    written = Counter()
    sites = []
    for call in candidate.get("calls", []):
        if call.get("copy"):
            continue
        token = callee_token(call["name"])
        if token is None or token.startswith("dtor:"):
            continue
        written[token] += 1
        sites.append((statement_of.get(call["offset"], call["line"]) - base, token))
    direct = compiled["direct"] if compiled else None
    for line, token in sites:
        inlined = direct is not None and not direct.get(token)
        view["calls_by_line"][line].append(("inline:" if inlined else "") + token)
    for token in set(written) | set(direct or ()):
        if direct is None:
            view["callees"][token]["calls"] = written[token]
            continue
        view["callees"][token]["calls"] = direct.get(token, 0)
        view["callees"][token]["inline"] = max(0, written[token] - direct.get(token, 0))
    if compiled:
        view["control"] = compiled["control"]

    lines = source.splitlines()
    first = min(base, candidate.get("line", base))
    text_rows, in_comment = [], False
    statements = {row["line"]: row["kind"] for row in layout["statements"]}
    for number in range(first, min(layout["end_line"], len(lines)) + 1):
        kind, in_comment = _line_class(lines[number - 1], in_comment)
        if number in statements:
            kind = "stmt"
        elif kind == "code":
            kind = "cont"
        text_rows.append(f"{number - base:+04d} {kind:<12}| {lines[number - 1]}")
    view["line_classes"] = Counter(row.split()[1] for row in text_rows)
    reference = ["// Our definition (relative line, class, text). Classes: stmt = a statement",
                 "// begins here (or the prolog/epilog brace); cont = continuation, else or",
                 "// case label; blank, comment, brace, preprocessor.", *text_rows]
    if compiled:
        reference += ["", "// Our compiled x86 basic blocks (homm3 sema skeleton):",
                      *("// " + row for row in compiled["skeleton"].rstrip().splitlines())]
    view["reference"] = "\n".join(reference) + "\n"
    return view


# --- pairing and rendering -----------------------------------------------------------

def pair_locals(dc: list[dict], ours: list[dict]) -> None:
    """Give paired locals one shared `key` (the Dreamcast name's folded spelling)."""
    ours_only, dc_only, matched = dc_diff_locals.diff_locals(dc, ours)
    for left, right in matched:
        left["key"] = right["key"] = semantic_name_key(left["name"])
        left["paired"] = right["paired"] = True
    for local in ours_only + dc_only:
        local["key"] = semantic_name_key(local["name"])
        local["paired"] = False


def render(view: dict[str, Any], header: list[str], line_range: tuple[int, int]) -> str:
    rows = [BANNER, *view["provenance"], *header, ""]

    def section(title: str, body: list[str]) -> None:
        rows.append(f"== {title} ==")
        rows.extend(body or ["(none)"])
        rows.append("")

    section("SIGNATURE", [view["signature"]])
    section(f"PARAMETERS ({len(view['parameters'])})",
            [f"{i}: {typ} {name}" for i, (name, typ) in enumerate(view["parameters"])])
    locals_ = sorted(view["locals"], key=lambda v: (v["key"], v["type"], v["scope"]))
    section(f"LOCALS ({len(locals_)})",
            [f"{v['key']}: {v['type']} @{v['scope']}" for v in locals_])
    section(f"TEMPORARIES WITH DESTRUCTORS ({sum(view['temporaries'].values())})",
            [f"{key} x{count}" for key, count in sorted(view["temporaries"].items())])
    other = view["other_temporaries"]
    section(f"OTHER TEMPORARIES ({sum(other.values())}; ours only, Dreamcast cannot record them)",
            [f"{key} x{count}" for key, count in sorted(other.items())])
    distinct = len({scope["key"] for scope in view["scopes"]})
    section(f"SCOPES ({len(view['scopes'])}; distinct extents {distinct})",
            ["  " * scope["depth"] + span_label(scope["span"]) for scope in view["scopes"]])
    runs, missing = statement_runs(view["statement_lines"])
    first, last = line_range
    section(f"LINES {first:+04d}..{last:+04d} (statement lines {len(view['statement_lines'])}; "
            f"non-statement runs {runs}, lines {missing})",
            [f"{line:+04d} {'stmt' if line in view['statement_lines'] else '-'}"
             for line in range(first, last + 1)])
    section("CALLS BY LINE (relative statement line; inline: = Dreamcast inline evidence, "
            "or our written call with no direct x86 call: expanded or virtual)",
            [f"{line:+04d} {' '.join(sorted(tokens))}"
             for line, tokens in sorted(view["calls_by_line"].items()) if tokens])
    section("STATEMENT SEQUENCE (no line numbers or inline marks: diff aligns statements by written calls)",
            [("stmt " + " ".join(sorted(token.removeprefix("inline:")
                                        for token in view["calls_by_line"].get(line, ())))).rstrip()
             for line in sorted(view["statement_lines"])])
    section("CALLS BY CALLEE (emitted direct calls / inline expansions)",
            [f"{token}: calls {row['calls']} inline {row['inline']}"
             for token, row in sorted(view["callees"].items())])
    control = view["control"]
    section("CONTROL FLOW (inferred basic blocks; SH4 versus x86, counts only)",
            [f"{key}: {value}" for key, value in control.items()] if control else ["(unavailable)"])
    if view["gaps"]:
        section("COVERAGE GAPS", sorted(set(view["gaps"])))
    rows.append("== REFERENCE (side-specific; not aligned) ==")
    rows.append(view["reference"].rstrip())
    return "\n".join(rows) + "\n"


def _callee_totals(view: dict[str, Any]) -> Counter:
    totals = Counter()
    for token, row in view["callees"].items():
        if not token.startswith("dtor:"):
            for key in token.split("|"):
                totals[key] += row["calls"] + row["inline"]
    return totals


def summarize(dc: dict[str, Any], ours: dict[str, Any], line_range: tuple[int, int]) -> dict[str, Any]:
    counts: dict[str, tuple[Any, Any]] = {}
    for name, key in (("statement lines", "statement_lines"), ("parameters", "parameters"),
                      ("locals", "locals"), ("scopes", "scopes")):
        counts[name] = (len(dc[key]), len(ours[key]))
    counts["distinct scope extents"] = tuple(len({s["key"] for s in v["scopes"]}) for v in (dc, ours))
    counts["non-statement runs"] = tuple(statement_runs(v["statement_lines"])[0] for v in (dc, ours))
    counts["non-statement lines"] = tuple(statement_runs(v["statement_lines"])[1] for v in (dc, ours))
    counts["temporaries with destructors"] = tuple(sum(v["temporaries"].values()) for v in (dc, ours))
    counts["inline expansions"] = tuple(sum(r["inline"] for r in v["callees"].values()) for v in (dc, ours))
    counts["emitted direct calls"] = tuple(sum(r["calls"] for r in v["callees"].values()) for v in (dc, ours))
    for key in ("blocks", "conditional branches", "back edges"):
        counts["cfg " + key] = tuple((v["control"] or {}).get(key) for v in (dc, ours))
    first, last = line_range
    mismatched = [line for line in range(first, last + 1)
                  if (line in dc["statement_lines"]) != (line in ours["statement_lines"])]
    locals_ours = sorted(f"{v['type']} {v['name']}" for v in ours["locals"] if not v["paired"])
    locals_dc = sorted(f"{v['type']} {v['name']}" for v in dc["locals"] if not v["paired"])
    local_types = sorted(f"{v['key']}: {v['type']} / {w['type']}"
                         for v in dc["locals"] if v["paired"]
                         for w in ours["locals"] if w["paired"] and w["key"] == v["key"]
                         and not same_type(v["type"], w["type"]))
    temps = sorted((set(dc["temporaries"]) | set(ours["temporaries"])))
    temporaries = {key: (dc["temporaries"].get(key, 0), ours["temporaries"].get(key, 0))
                   for key in temps if dc["temporaries"].get(key, 0) != ours["temporaries"].get(key, 0)}
    left, right = _callee_totals(dc), _callee_totals(ours)
    callees = {key: (left.get(key, 0), right.get(key, 0))
               for key in sorted(set(left) | set(right)) if left.get(key, 0) != right.get(key, 0)}
    parameter_types = [f"{i}: {a[1]} / {b[1]}" for i, (a, b) in
                       enumerate(zip(dc["parameters"], ours["parameters"])) if not same_type(a[1], b[1])]
    score = (abs(counts["statement lines"][0] - counts["statement lines"][1])
             + abs(counts["scopes"][0] - counts["scopes"][1])
             + abs(counts["parameters"][0] - counts["parameters"][1])
             + len(locals_ours) + len(locals_dc)
             + sum(abs(a - b) for a, b in temporaries.values())
             + sum(abs(a - b) for a, b in callees.values()))
    return {"counts": counts, "line_mismatches": len(mismatched),
            "mismatched_lines": mismatched, "locals_ours_only": locals_ours,
            "locals_dc_only": locals_dc, "local_type_differences": local_types,
            "parameter_type_differences": parameter_types,
            "signature_differs": not same_type(dc["signature"], ours["signature"]),
            "temporaries": temporaries, "callees": callees, "difference": score}


def render_summary(identity: dict[str, Any], summary: dict[str, Any]) -> str:
    rows = [f"function: {identity['name']}", f"retail: 0x{identity['va']:08x}  unit: {identity['unit']}  "
            f"score: {dc_diff_locals._score_text(identity['score'])}",
            f"dreamcast: {identity['module']} dc:0x{identity['dc_offset']:x}  source: {identity['source']}",
            f"structural difference: {summary['difference']} "
            "(|d statement lines| + |d scopes| + |d params| + unpaired locals"
            " + temporary and callee count differences)", "",
            f"{'count':<30} {'dc':>6} {'ours':>6} {'delta':>6}"]
    for name, (a, b) in summary["counts"].items():
        delta = "" if a is None or b is None else f"{b - a:+d}"
        rows.append(f"{name:<30} {'-' if a is None else a:>6} {'-' if b is None else b:>6} {delta:>6}")
    rows.append(f"{'line class mismatches':<30} {'':>6} {'':>6} {summary['line_mismatches']:>6}")
    if summary["signature_differs"]:
        rows.append("\nsignature differs (see SIGNATURE)")
    for title, key in (("parameter types (dc / ours)", "parameter_type_differences"),
                       ("locals only ours declares", "locals_ours_only"),
                       ("locals only Dreamcast records", "locals_dc_only"),
                       ("paired local types (dc / ours)", "local_type_differences")):
        if summary[key]:
            rows.append(f"\n{title}:")
            rows.extend("  " + item for item in summary[key])
    if summary["temporaries"]:
        rows.append("\ntemporaries with destructors (dc ours):")
        rows.extend(f"  {key} {a} {b}" for key, (a, b) in summary["temporaries"].items())
    if summary["callees"]:
        rows.append("\ncallees, calls + inline expansions (dc ours):")
        rows.extend(f"  {key} {a} {b}" for key, (a, b) in summary["callees"].items())
    return "\n".join(rows) + "\n"


# --- driver ------------------------------------------------------------------------------

def _safe(text: str) -> str:
    return re.sub(r"[^A-Za-z0-9_.-]+", "_", text).strip("_") or "function"


def _read_manifest(output: Path) -> list[str]:
    manifest = output / "index.json"
    if output.exists() and any(output.iterdir()) and not manifest.is_file():
        raise dreamcast.DreamcastError(f"{output}: nonempty directory is not a compare export; choose --output")
    if not manifest.exists():
        return []
    try:
        previous = json.loads(manifest.read_text())
        if previous["schema"] != SCHEMA:
            raise ValueError("unrecognized generator")
        files = previous["files"]
        if any(Path(name).is_absolute() or ".." in Path(name).parts for name in files):
            raise ValueError("invalid generated file paths")
        return files
    except (KeyError, ValueError, TypeError) as exc:
        raise dreamcast.DreamcastError(f"{manifest}: invalid export manifest: {exc}") from exc


def _score_value(score: dict | None, key: str) -> float:
    return -1.0 if score is None or score.get(key) is None else score[key]


def select(corpus, args) -> list[dict[str, Any]]:
    pairs = dc_diff_locals.paired(corpus, selectors=args.selectors, units=args.unit or (),
                                  modules=args.module or (), all_functions=args.all)
    ledger, sources = dc_diff_locals.ledger_by_va(), dc_diff_locals.unit_sources()
    by_path = {path: unit for unit, path in sources.items()}
    items = []
    for row, claim in pairs:
        score = dc_diff_locals.score_for(claim.va, claim.path, ledger, sources)
        if args.non_exact and (score is None or score["max"] is None or score["max"] >= 100):
            continue
        items.append({"row": row, "claim": claim, "score": score,
                      "unit": score["unit"] if score else by_path.get(claim.path, "-")})
    items.sort(key=lambda item: (-_score_value(item["score"], "max"), item["claim"].va))
    if args.limit < 0:
        raise dreamcast.DreamcastError("--limit must be >= 0")
    if args.limit:
        items = items[:args.limit]
    if not items:
        raise dreamcast.NoMatch("no Dreamcast-paired functions left after --non-exact/--limit")
    return items


def export(corpus, items: list[dict[str, Any]], output: Path) -> dict[str, Any]:
    from homm3.analysis import dc_lines, source_facts
    from homm3.core import common, inputs
    from homm3.core.nb11_types import Types
    from homm3.core.project import Project
    from homm3.sema import _asm
    output = Path(output)
    if output.is_symlink() or (output.exists() and not output.is_dir()):
        raise dreamcast.DreamcastError(f"{output}: expected an ordinary output directory")
    previous = _read_manifest(output)
    symbols, data = dc_lines.load_symbols(), inputs.read_dreamcast_exe()
    types = Types.from_symbols(symbols)
    project = Project(common.HOMM3_DIR)
    parser = source_facts.CandidateParser(project.root, batch=len(items) > 1, project=project)
    objects = ObjectCalls()
    sources = dc_diff_locals.unit_sources()
    index = {"schema": SCHEMA, "generator": GENERATOR, "caution": CAUTION,
             "functions": [], "files": []}
    names: Counter = Counter()
    output.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix=".dreamcast-compare-", dir=output.parent) as temp:
        stage = Path(temp)

        def write(name: str, content: str) -> None:
            path = stage / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            index["files"].append(name)

        for item in sorted(items, key=lambda item: (item["claim"].path, item["claim"].va)):
            row, claim = item["row"], item["claim"]
            identity = {"va": claim.va, "name": row["name"], "module": row["module"],
                        "dc_offset": dreamcast._integer(row["offset"]), "source": claim.path,
                        "unit": item["unit"], "score": item["score"]}
            stem = f"{claim.va:08x}_{_safe(row['name'])}"
            names[(item["unit"], stem)] += 1
            if names[(item["unit"], stem)] > 1:
                stem += f"_dc{identity['dc_offset']:x}"
            identity["stem"] = f"{_safe(item['unit'])}/{stem}"
            dc = dreamcast_view(corpus, row, symbols=symbols, data=data, types=types)
            ours = _empty_view("ours")
            mangled = corpus._retail_name(claim.va - common.IMAGE_BASE)
            try:
                if not mangled:
                    raise ValueError("retail/source symbol binding unavailable; run homm3 build")
                unit_source = sources.get(item["unit"])
                candidate = parser(common.HOMM3_DIR / claim.path, mangled,
                                   common.HOMM3_DIR / unit_source if unit_source else None)
                obj = _asm.BASE / f"{item['unit']}.obj"
                text = objects.body(obj, mangled)
                compiled = compiled_facts(text, objects.qualified(obj)) if text else None
                note = (f"compiled {obj.relative_to(common.HOMM3_DIR)} as last built" if compiled
                        else "compiled body unavailable (run homm3 build)")
                ours = our_view(candidate, (common.HOMM3_DIR / claim.path).read_text(errors="replace"),
                                compiled, object_note=note, display_path=claim.path)
            except (ValueError, OSError, subprocess.SubprocessError, json.JSONDecodeError) as exc:
                ours["provenance"] = [f"// SIDE: ours {claim.path}; definition unavailable"]
                ours["gaps"].append(str(exc).splitlines()[0])
            pair_locals(dc["locals"], ours["locals"])
            lines = dc["statement_lines"] | ours["statement_lines"] | {0}
            line_range = (min(lines), max(lines))
            header = [f"// FUNCTION: {row['name']}; retail 0x{claim.va:08x}; unit {item['unit']}; "
                      f"{dc_diff_locals._score_text(item['score'])}",
                      "// " + CAUTION]
            summary = summarize(dc, ours, line_range)
            write(f"{identity['stem']}.dc.cpp", render(dc, header, line_range))
            write(f"{identity['stem']}.ours.cpp", render(ours, header, line_range))
            write(f"{identity['stem']}.summary", render_summary(identity, summary))
            index["functions"].append({**identity, "summary": summary,
                                       "ours_available": bool(ours["signature"])})
        index["functions"].sort(key=lambda f: (-_score_value(f["score"], "max"), f["va"]))
        write("index.tsv", render_index_tsv(index["functions"]))
        write("index.md", render_index_md(index["functions"]))
        index["files"].append("index.json")
        (stage / "index.json").write_text(json.dumps(index, indent=1, default=list) + "\n",
                                          encoding="utf-8")
        for name in set(previous) | set(index["files"]):
            path = output / name
            if any(p.is_symlink() for p in (path, *path.parents)):
                raise dreamcast.DreamcastError(f"refusing to write through a symlink: {path}")
        output.mkdir(exist_ok=True)
        for name in index["files"]:
            path = output / name
            path.parent.mkdir(parents=True, exist_ok=True)
            (stage / name).replace(path)
        for name in set(previous) - set(index["files"]):
            (output / name).unlink(missing_ok=True)
        for directory in sorted({(output / name).parent for name in previous}, reverse=True):
            if directory != output and directory.is_dir() and not any(directory.iterdir()):
                directory.rmdir()
    return index


INDEX_COLUMNS = ("va", "name", "unit", "cur", "max", "difference", "d_statements", "d_scopes",
                 "ours_only_locals", "dc_only_locals", "d_temporaries", "callee_differences",
                 "line_mismatches", "files")


def _index_rows(functions: list[dict]) -> Iterable[list[str]]:
    for f in functions:
        s, score = f["summary"], f["score"] or {}
        counts = s["counts"]
        yield [f"0x{f['va']:08x}", f["name"], f["unit"],
               "-" if score.get("cur") is None else f"{score['cur']:.2f}",
               "-" if score.get("max") is None else f"{score['max']:.2f}",
               str(s["difference"]),
               f"{counts['statement lines'][1] - counts['statement lines'][0]:+d}",
               f"{counts['scopes'][1] - counts['scopes'][0]:+d}",
               str(len(s["locals_ours_only"])), str(len(s["locals_dc_only"])),
               str(sum(abs(a - b) for a, b in s["temporaries"].values())),
               str(len(s["callees"])), str(s["line_mismatches"]), f["stem"]]


def render_index_tsv(functions: list[dict]) -> str:
    return "\n".join("\t".join(row) for row in [list(INDEX_COLUMNS), *_index_rows(functions)]) + "\n"


def patterns(functions: list[dict]) -> list[str]:
    """Aggregate tallies: how many functions show each kind of difference."""
    def count(predicate) -> int:
        return sum(1 for f in functions if predicate(f["summary"]))
    c = lambda s, key: s["counts"][key]
    rows = [
        f"- {count(lambda s: s['locals_ours_only'])} functions declare a local Dreamcast does not record "
        f"({sum(len(f['summary']['locals_ours_only']) for f in functions)} locals)",
        f"- {count(lambda s: s['locals_dc_only'])} functions lack a local Dreamcast records "
        f"({sum(len(f['summary']['locals_dc_only']) for f in functions)} locals)",
        f"- {count(lambda s: s['local_type_differences'])} functions have a paired local of another type",
        f"- {count(lambda s: s['parameter_type_differences'])} functions have a parameter of another type",
        f"- {count(lambda s: c(s, 'scopes')[0] > c(s, 'scopes')[1])} functions have fewer scopes "
        "than Dreamcast records; "
        f"{count(lambda s: c(s, 'scopes')[0] < c(s, 'scopes')[1])} have more",
        f"- {count(lambda s: c(s, 'statement lines')[0] > c(s, 'statement lines')[1])} functions have "
        "fewer statement lines than Dreamcast records; "
        f"{count(lambda s: c(s, 'statement lines')[0] < c(s, 'statement lines')[1])} have more",
        f"- {count(lambda s: any(b > a for a, b in s['temporaries'].values()))} functions have an extra "
        "destructor-carrying temporary; "
        f"{count(lambda s: any(a > b for a, b in s['temporaries'].values()))} lack one",
        f"- {count(lambda s: c(s, 'inline expansions')[0] > 0)} functions show Dreamcast inline expansions; "
        f"{count(lambda s: c(s, 'inline expansions')[1] > 0)} of ours expand a written call",
    ]
    more, fewer = Counter(), Counter()
    for f in functions:
        for key, (a, b) in f["summary"]["callees"].items():
            (more if b > a else fewer)[key] += 1
    rows.append("- callees ours calls/expands more often (functions): "
                + ", ".join(f"{k} {n}" for k, n in more.most_common(15)))
    rows.append("- callees Dreamcast calls/expands more often (functions): "
                + ", ".join(f"{k} {n}" for k, n in fewer.most_common(15)))
    types = Counter(t.rsplit(" ", 1)[0] for f in functions for t in f["summary"]["locals_ours_only"])
    rows.append("- types of locals only ours declares: "
                + ", ".join(f"{k} {n}" for k, n in types.most_common(12)))
    types = Counter(t.rsplit(" ", 1)[0] for f in functions for t in f["summary"]["locals_dc_only"])
    rows.append("- types of locals only Dreamcast records: "
                + ", ".join(f"{k} {n}" for k, n in types.most_common(12)))
    return rows


def render_index_md(functions: list[dict]) -> str:
    rows = ["# Dreamcast versus our source structure", "",
            f"Generated by `{GENERATOR}`. {CAUTION}", "",
            "Each function has `<fn>.dc.cpp` and `<fn>.ours.cpp` with one shared section layout",
            "(`diff -u` or a side-by-side viewer lines them up) and a `<fn>.summary`.",
            "Line numbers are relative to the opening brace (Dreamcast: the procedure boundary row).",
            "`difference` = |d statement lines| + |d scopes| + |d parameters| + unpaired",
            "locals + temporary and callee count differences.", "",
            "## Repeating patterns", "", *patterns(functions), "",
            "## Functions (by MAX, descending)", "",
            "| " + " | ".join(INDEX_COLUMNS) + " |",
            "|" + "---|" * len(INDEX_COLUMNS)]
    for row in _index_rows(functions):
        stem = row[-1]
        row[-1] = (f"[dc]({stem}.dc.cpp) [ours]({stem}.ours.cpp) [summary]({stem}.summary)")
        rows.append("| " + " | ".join(cell.replace("|", "\\|") for cell in row) + " |")
    return "\n".join(rows) + "\n"


def run(corpus, args) -> int:
    from homm3.core import common
    items = select(corpus, args)
    output = args.output if args.output.is_absolute() else common.HOMM3_DIR / args.output
    index = export(corpus, items, output)
    functions = index["functions"]
    unavailable = sum(not f["ours_available"] for f in functions)
    print(f"[homm3 dreamcast] compare-structure: {len(functions)} function(s)"
          + (f", {unavailable} without our definition" if unavailable else "")
          + f" -> {output / 'index.md'}")
    return 0


def add_parser(sub) -> None:
    from homm3.core import common
    parser = sub.add_parser(
        "compare-structure",
        help="aligned Dreamcast/ours structure files per paired function")
    parser.add_argument("selectors", nargs="*", metavar="SELECTOR",
                        help="retail VA/RVA, dc:OFF, module:OFF, or name; repeatable")
    scope = parser.add_mutually_exclusive_group()
    scope.add_argument("--unit", action="append", metavar="UNIT",
                       help="build unit (config/units.toml); repeatable")
    scope.add_argument("--module", action="append", metavar="MODULE",
                       help="Dreamcast module[.obj]; repeatable")
    scope.add_argument("--all", action="store_true", help="every Dreamcast-paired function")
    parser.add_argument("--non-exact", action="store_true",
                        help="only functions whose ledger MAX is below 100%%")
    parser.add_argument("--limit", type=int, default=0,
                        help="only the N highest-MAX functions (default 0 = all)")
    parser.add_argument("--output", type=Path, default=common.HOMM3_DIR / "build/dreamcast/compare",
                        help="generated tree (default build/dreamcast/compare)")
